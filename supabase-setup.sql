-- Run this in Supabase: SQL Editor -> New query -> Run.
create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  email text not null,
  location text not null,
  category text not null,
  message text not null
);

alter table public.reports enable row level security;

-- Allow visitors to submit a report from the public website.
create policy "Anyone can submit a report"
on public.reports
for insert
to anon
with check (
  char_length(name) between 1 and 80
  and char_length(email) between 3 and 120
  and char_length(location) between 1 and 120
  and char_length(message) between 1 and 1500
);

-- No public SELECT policy is created: visitors cannot read submitted reports.
